-- The task names tables and columns in camelCase (timeDeposits, planType, timeDepositId).
-- PostgreSQL folds unquoted identifiers to lowercase, so the schema uses snake_case with a 1:1 mapping.

create table time_deposits (
    id        integer primary key generated by default as identity,
    plan_type varchar(20) not null check (plan_type in ('basic', 'student', 'premium')),
    days      integer not null,
    balance   numeric(19, 2) not null
);

create table withdrawals (
    id              integer primary key generated by default as identity,
    time_deposit_id integer not null references time_deposits (id),
    amount          numeric(19, 2) not null,
    date            date not null
);

create index idx_withdrawals_time_deposit_id on withdrawals (time_deposit_id);
